"""Alembic environment. The database URL comes from chamapro.config
(DATABASE_URL, else the SQLite file), unless init_db() hands over a connection.

Migrations are written by hand, not autogenerated: the immutability triggers
and the pre-Alembic baseline need dialect-specific SQL that autogenerate
cannot see.
"""
from logging.config import fileConfig

from alembic import context
from sqlalchemy import create_engine, pool

from chamapro import config as chamapro_config

cfg = context.config
if cfg.config_file_name is not None and cfg.attributes.get("connection") is None:
    fileConfig(cfg.config_file_name, disable_existing_loggers=False)


def url() -> str:
    return cfg.get_main_option("sqlalchemy.url") or chamapro_config.DATABASE_URL


def run_offline() -> None:
    """`alembic upgrade head --sql`: print the SQL instead of running it."""
    context.configure(url=url(), literal_binds=True, dialect_opts={"paramstyle": "named"})
    with context.begin_transaction():
        context.run_migrations()


def run_online() -> None:
    conn = cfg.attributes.get("connection")
    if conn is not None:                       # init_db(): its transaction, its connection
        context.configure(connection=conn)
        context.run_migrations()
        return
    engine = create_engine(url(), poolclass=pool.NullPool)
    with engine.connect() as conn:
        context.configure(connection=conn)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_offline()
else:
    run_online()
